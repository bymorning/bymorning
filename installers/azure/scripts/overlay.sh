#!/bin/sh
# Generates a Kustomize overlay from Terraform outputs.
#
# Usage:
#   terraform -chdir=installers/azure/environments/<root> output -json > outputs.json
#   sh installers/azure/scripts/overlay.sh outputs.json <name> \
#      --host bymorning.contoso.us --image myregistry.azurecr.us/bymorning@sha256:<digest> \
#      [--aws-role-arn arn:<partition>:iam::<account>:role/<name> --aws-region <region>] \
#      [--component bedrock-web-identity|bedrock-api-key|code-interpreter-kubernetes]...
#
# Writes k8s/overlays/<name>/kustomization.yaml (git-ignored for names other than
# "example"). Contains no secrets. Requires jq.
set -eu

k8s=$(CDPATH= cd -- "$(dirname "$0")/../k8s" && pwd)
[ $# -ge 2 ] || { sed -n '2,12p' "$0" >&2; exit 2; }
outputs=$1
name=$2
shift 2

host=""
image=""
role=""
region=""
components=""
while [ $# -gt 0 ]; do
  case $1 in
    --host) host=$2; shift 2 ;;
    --image) image=$2; shift 2 ;;
    --aws-role-arn) role=$2; shift 2 ;;
    --aws-region) region=$2; shift 2 ;;
    --component) components="$components $2"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
[ -n "$host" ] || { echo "--host is required" >&2; exit 2; }
[ -n "$image" ] || { echo "--image is required" >&2; exit 2; }
case $name in */*|"" ) echo "overlay name must be a plain directory name" >&2; exit 2 ;; esac
for c in $components; do
  [ -d "$k8s/components/$c" ] || { echo "unknown component: $c" >&2; exit 2; }
  case $c in
    bedrock-web-identity) { [ -n "$role" ] && [ -n "$region" ]; } || { echo "$c needs --aws-role-arn and --aws-region" >&2; exit 2; } ;;
    bedrock-api-key) [ -n "$region" ] || { echo "$c needs --aws-region" >&2; exit 2; } ;;
  esac
done

out() { jq -er --arg k "$1" '.[$k].value | select(. != null)' "$outputs" || { echo "missing Terraform output: $1" >&2; exit 1; }; }

client=$(out gateway_client_id)
tenant=$(out tenant_id)
cloud=$(out azure_cloud)
storage=$(out storage_account_url)
container=$(out storage_container)
key=$(out key_vault_key)

case $image in
  *@sha256:*) repo=${image%@*}; ref="digest: ${image#*@}" ;;
  *:*) repo=${image%:*}; ref="newTag: ${image##*:}" ;;
  *) repo=$image; ref="newTag: azure" ;;
esac

dir="$k8s/overlays/$name"
mkdir -p "$dir"
{
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "# Generated by scripts/overlay.sh from Terraform outputs. Contains no secrets."
  echo "resources:"
  echo "  - ../../base"
  if [ -n "$components" ]; then
    echo "components:"
    for c in $components; do echo "  - ../../components/$c"; done
  fi
  echo "configMapGenerator:"
  echo "  - name: bymorning-env"
  echo "    behavior: merge"
  echo "    literals:"
  echo "      - APP_ORIGIN=https://$host"
  echo "      - AZURE_CLOUD=$cloud"
  echo "      - STORAGE_ACCOUNT_URL=$storage"
  echo "      - STORAGE_CONTAINER=$container"
  echo "      - KEY_VAULT_KEY=$key"
  if [ -n "$role$region" ]; then
    echo "  - name: bymorning-aws"
    # The base kustomization's namespace does not reach a generator added by the overlay.
    echo "    namespace: bymorning"
    echo "    literals:"
    [ -z "$role" ] || echo "      - AWS_ROLE_ARN=$role"
    [ -z "$region" ] || echo "      - AWS_REGION=$region"
    # The image no longer bakes the FIPS flag; Bedrock in a GovCloud partition needs it.
    case $region in us-gov-*) echo "      - AWS_USE_FIPS_ENDPOINT=true" ;; esac
    if [ -n "$role" ]; then
      echo "      - AWS_WEB_IDENTITY_TOKEN_FILE=/var/run/secrets/aws/token"
      echo "      - AWS_ROLE_SESSION_NAME=bymorning-gateway"
      echo "      - AWS_EC2_METADATA_DISABLED=true"
    fi
  fi
  echo "images:"
  echo "  - name: bymorning"
  echo "    newName: $repo"
  echo "    $ref"
  echo "patches:"
  echo "  - target:"
  echo "      kind: ServiceAccount"
  echo "      name: bymorning-gateway"
  echo "    patch: |-"
  echo "      - op: replace"
  echo "        path: /metadata/annotations/azure.workload.identity~1client-id"
  echo "        value: $client"
  echo "      - op: replace"
  echo "        path: /metadata/annotations/azure.workload.identity~1tenant-id"
  echo "        value: $tenant"
  echo "  - target:"
  echo "      kind: Ingress"
  echo "      name: bymorning"
  echo "    patch: |-"
  echo "      - op: replace"
  echo "        path: /spec/rules/0/host"
  echo "        value: $host"
  echo "      - op: replace"
  echo "        path: /spec/tls/0/hosts/0"
  echo "        value: $host"
} > "$dir/kustomization.yaml"
echo "wrote $dir/kustomization.yaml"
