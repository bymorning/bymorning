import { readFile, writeFile } from "node:fs/promises"

import byMorningJson from "../src/theme/themes/bymorning.json"
import inkJson from "../src/theme/themes/ink.json"
import paperJson from "../src/theme/themes/paper.json"
import { fontsToCss } from "../src/theme/font"
import { ALPHA_FOUNDATION, AVATAR_FOUNDATION } from "../src/theme/foundation"
import { resolveTheme } from "../src/theme/resolve"
import { ALPHA_TOKENS, AVATAR_TOKENS, NON_ALPHA_PRIMITIVE_TOKENS, THEME_SEMANTIC_TOKENS } from "../src/theme/tokens"
import type { ThemeMode, TokenValue } from "../src/theme/types"
import { requireTheme } from "../src/theme/validate"

const themes = [requireTheme(byMorningJson), requireTheme(inkJson), requireTheme(paperJson)]
const resolvedThemes = themes.map((theme) => ({ theme, resolved: resolveTheme(theme) }))
const generatedHeader = "/* This file is generated by scripts/generate-theme-css.ts. Do not edit. */"
const colorsCss = `${generatedHeader}
@layer theme {
  :root {
    ${tokensToCss(ALPHA_FOUNDATION, ALPHA_TOKENS)}
  }

${(["light", "dark"] as const)
  .map(
    (mode) =>
      `  :root[data-color-scheme="${mode}"] {
    ${tokensToCss(AVATAR_FOUNDATION[mode], AVATAR_TOKENS)}
  }`,
  )
  .join("\n\n")}

${resolvedThemes
  .flatMap(({ theme, resolved }) =>
    (["light", "dark"] as const).map(
      (mode) =>
        `  :root[data-theme="${theme.id}"][data-color-scheme="${mode}"] {
    ${tokensToCss(resolved[mode], NON_ALPHA_PRIMITIVE_TOKENS)}
  }`,
    ),
  )
  .join("\n\n")}
}
`
const themeCss = `${generatedHeader}
@layer theme {
${resolvedThemes.map(({ theme, resolved }) => themeBlocks(theme.id, resolved)).join("\n\n")}
}
`
const outputs = [
  [new URL("../src/theme/styles/tokens/colors.css", import.meta.url), colorsCss],
  [new URL("../src/theme/styles/tokens/theme.css", import.meta.url), themeCss],
  [new URL("../src/theme/styles/fonts.css", import.meta.url), fontsToCss()],
] as const

if (process.argv.includes("--check")) {
  const stale = []
  for (const [path, expected] of outputs) {
    if ((await readFile(path, "utf8").catch(() => "")) !== expected) stale.push(path.pathname)
  }
  if (stale.length > 0) {
    console.error(`Generated theme CSS is stale: ${stale.join(", ")}. Run \`bun run theme:generate\` in packages/ui.`)
    process.exit(1)
  }
} else {
  for (const [path, content] of outputs) await writeFile(path, content)
}

function themeBlocks(id: string, resolved: Readonly<Record<ThemeMode, Readonly<Record<string, TokenValue>>>>) {
  return (["light", "dark"] as const)
    .map(
      (mode) =>
        `  /* prettier-ignore */
  :root[data-theme="${id}"][data-color-scheme="${mode}"] {
    color-scheme: ${mode};
    ${tokensToCss(resolved[mode], THEME_SEMANTIC_TOKENS)}
  }`,
    )
    .join("\n\n")
}

function tokensToCss(tokens: Readonly<Record<string, TokenValue>>, inventory: readonly string[]) {
  return inventory
    .map((key) => {
      const value = tokens[key]
      if (value === undefined) throw new Error(`Missing theme token: ${key}`)
      return `--${key}: ${value};`
    })
    .join("\n    ")
}
