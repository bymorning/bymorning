interface FontFace {
  readonly source: string
  readonly format: "truetype" | "woff2"
  readonly weight: string
  readonly style: "normal" | "italic"
}

interface FontDefinition {
  readonly family: string
  readonly fallback: "sans-serif" | "monospace"
  readonly faces: readonly FontFace[]
}

const atkinsonFace = (file: string, weight: string, style: FontFace["style"]): FontFace => ({
  source: `../../assets/fonts/AtkinsonHyperlegibleNext/${file}`,
  format: "woff2",
  weight,
  style,
})

