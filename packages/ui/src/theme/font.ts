export type FontID = keyof typeof FONTS

/** Whether a serialized value names a registered local font. */
export function isFontID(value: unknown): value is FontID {
  return typeof value === "string" && Object.hasOwn(FONTS, value)
}

/** Resolve a registered font ID to its CSS family stack. */
export function fontFamily(id: FontID): string {
  const font = FONTS[id]
  return `"${font.family}", ${font.fallback}`
}

/** Render every registered face without causing unused faces to download. */
export function fontsToCss(): string {
  const faces = Object.values(FONTS).flatMap((font) =>
    font.faces.map(
      (face) =>
        `@font-face {\n  font-family: "${font.family}";\n  src: url("${face.source}") format("${face.format}");\n  font-weight: ${face.weight};\n  font-style: ${face.style};\n  font-display: swap;\n}`,
    ),
  )
  return `/* This file is generated by scripts/generate-theme-css.ts. Do not edit. */\n${faces.join("\n\n")}\n`
}
