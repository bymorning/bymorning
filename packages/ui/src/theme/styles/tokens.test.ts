/// <reference types="node" />

import { existsSync, readdirSync, readFileSync, statSync } from "node:fs"
import { join, relative } from "node:path"
import { describe, expect, it } from "vitest"

import { FONTS } from "../font"
import { resolveTheme } from "../resolve"
import byMorningJson from "../themes/bymorning.json"
import inkJson from "../themes/ink.json"
import paperJson from "../themes/paper.json"
import {
  ALPHA_TOKENS,
  AVATAR_TOKENS,
  CANONICAL_TOKENS,
  NON_ALPHA_PRIMITIVE_TOKENS,
  THEME_SCOPED_TOKENS,
  THEME_SEMANTIC_TOKENS,
} from "../tokens"
import type { ThemeDefinition, ThemeMode } from "../types"
import { requireTheme } from "../validate"

const root = process.cwd()
const styles = join(root, "src/theme/styles")
const colorsCss = readFileSync(join(styles, "tokens/colors.css"), "utf8")
const themeCss = readFileSync(join(styles, "tokens/theme.css"), "utf8")
const fontsCss = readFileSync(join(styles, "fonts.css"), "utf8")
const definitions = [requireTheme(byMorningJson), requireTheme(inkJson), requireTheme(paperJson)]

function block(css: string, selector: string) {
  const start = css.indexOf(`${selector} {`)
  if (start === -1) throw new Error(`Missing CSS block for ${selector}`)
  return css.slice(css.indexOf("{", start) + 1, css.indexOf("\n  }", start))
}

function declarations(body: string) {
  return [...body.matchAll(/--([a-z0-9-]+)\s*:\s*([^;{}]+);/g)].map((match) => [match[1]!, match[2]!.trim()] as const)
}

function selectors(css: string) {
  return [...css.matchAll(/(?:^|\n)  (:root[^{}\n]*) \{\n/g)].map((match) => match[1]!)
}

function themeSelector(theme: ThemeDefinition, mode: ThemeMode) {
  return `:root[data-theme="${theme.id}"][data-color-scheme="${mode}"]`
}

function selected(theme: ThemeDefinition, mode: ThemeMode) {
  const entries = [
    ...declarations(block(colorsCss, ":root")),
    ...declarations(block(colorsCss, `:root[data-color-scheme="${mode}"]`)),
    ...declarations(block(colorsCss, themeSelector(theme, mode))),
    ...declarations(block(themeCss, themeSelector(theme, mode))),
  ]
  return { entries, map: Object.fromEntries(entries) }
}

const expectedThemeSelectors = definitions.flatMap((theme) =>
  (["light", "dark"] as const).map((mode) => themeSelector(theme, mode)),
)

describe("generated static theme architecture", () => {
  it("partitions the exact inventory without overlap", () => {
    expect(CANONICAL_TOKENS).toHaveLength(264)
    expect(ALPHA_TOKENS).toHaveLength(38)
    expect(AVATAR_TOKENS).toHaveLength(19)
    expect(NON_ALPHA_PRIMITIVE_TOKENS).toHaveLength(109)
    expect(THEME_SEMANTIC_TOKENS).toHaveLength(98)
    expect(THEME_SCOPED_TOKENS).toHaveLength(207)
    expect(new Set(CANONICAL_TOKENS)).toHaveLength(264)
    expect(new Set([...ALPHA_TOKENS, ...AVATAR_TOKENS, ...THEME_SCOPED_TOKENS])).toHaveLength(264)
  })

  it("has shared foundation plus exactly six primitive and six semantic selectors", () => {
    expect(selectors(colorsCss)).toEqual([
      ":root",
      ':root[data-color-scheme="light"]',
      ':root[data-color-scheme="dark"]',
      ...expectedThemeSelectors,
    ])
    expect(selectors(themeCss)).toEqual(expectedThemeSelectors)
    expect(colorsCss).not.toContain("color-scheme:")
    for (const theme of definitions) {
      for (const mode of ["light", "dark"] as const) {
        const body = block(themeCss, themeSelector(theme, mode))
        expect(body.match(/color-scheme:/g)).toHaveLength(1)
        expect(body).toMatch(new RegExp(`^\\n    color-scheme: ${mode};`))
      }
    }
  })

  it("is generated from all JSON inputs with no theme-specific artifact", () => {
    const generator = readFileSync(join(root, "scripts/generate-theme-css.ts"), "utf8")
    expect(generator).toContain('themes/bymorning.json"')
    expect(generator).toContain('themes/ink.json"')
    expect(generator).toContain('themes/paper.json"')
    expect(existsSync(join(styles, "ink.generated.css"))).toBe(false)
    expect(existsSync(join(root, "src/theme/bymorning.ts"))).toBe(false)
    for (const css of [colorsCss, themeCss, fontsCss]) {
      expect(css).toContain("generated by scripts/generate-theme-css.ts")
    }
  })

  it("matches the same resolver layers for all themes and modes", () => {
    for (const definition of definitions) {
      const resolved = resolveTheme(definition)
      for (const mode of ["light", "dark"] as const) {
        expect(Object.fromEntries(declarations(block(colorsCss, themeSelector(definition, mode))))).toEqual(
          Object.fromEntries(NON_ALPHA_PRIMITIVE_TOKENS.map((token) => [token, resolved[mode][token]])),
        )
        expect(Object.fromEntries(declarations(block(themeCss, themeSelector(definition, mode))))).toEqual(
          Object.fromEntries(THEME_SEMANTIC_TOKENS.map((token) => [token, resolved[mode][token]])),
        )
      }
    }
  })

  it("gives all six combinations 207 scoped and 264 effective unique tokens with resolved refs", () => {
    for (const definition of definitions) {
      const resolved = resolveTheme(definition)
      for (const mode of ["light", "dark"] as const) {
        expect(Object.keys(resolved[mode])).toHaveLength(207)
        const candidate = selected(definition, mode)
        const names = candidate.entries.map(([name]) => name)
        expect(candidate.entries).toHaveLength(264)
        expect(new Set(names)).toHaveLength(264)
        expect(new Set(names)).toEqual(new Set(CANONICAL_TOKENS))
        for (const [, value] of candidate.entries) {
          for (const reference of value.matchAll(/var\(--([a-z0-9-]+)\)/g)) {
            expect(candidate.map[reference[1]!], `${definition.id} ${mode}: ${reference[1]}`).toBeDefined()
          }
        }
      }
    }
  })

  it("registers local font assets", () => {
    for (const font of Object.values(FONTS)) {
      expect(fontsCss).toContain(`font-family: "${font.family}"`)
      for (const face of font.faces) {
        expect(face.source.startsWith("../../assets/fonts/")).toBe(true)
        expect(existsSync(join(styles, face.source))).toBe(true)
      }
    }
  })

  it("defines every production theme reference in every combination", () => {
    const references = new Set<string>()
    for (const path of walk(join(root, "src")).filter((item) => item.endsWith(".css"))) {
      for (const match of readFileSync(path, "utf8").matchAll(
        /var\(--((?:(?:color|shadow|font|button)-|radius)[a-z0-9-]*)/g,
      ))
        references.add(match[1]!)
    }
    for (const definition of definitions) {
      for (const mode of ["light", "dark"] as const) {
        const defined = new Set(selected(definition, mode).entries.map(([name]) => name))
        for (const reference of references)
          expect(defined.has(reference), `${definition.id} ${mode}: ${reference}`).toBe(true)
      }
    }
  })
})

describe("theme architecture guards", () => {
  it("keeps override and discriminator vocabulary out of build sources", () => {
    const sources = [
      ...walk(join(root, "src/theme")).filter((path) => path.endsWith(".ts") && !path.endsWith(".test.ts")),
      join(root, "scripts/generate-theme-css.ts"),
    ]
    for (const path of sources) {
      const source = readFileSync(path, "utf8")
      expect(source).not.toMatch(/\b(?:recipe|decisions|overrides|v2Overrides)\b/)
      expect(source).not.toContain("Object.assign")
    }
  })

  it("rejects versioned architecture and runtime CSS injection", () => {
    const sourceRoot = join(root, "src")
    const files = walk(sourceRoot).filter((path) => /\.(?:ts|tsx|css)$/.test(path) && !/\.test\.[^.]+$/.test(path))
    for (const path of files) {
      const name = relative(sourceRoot, path)
      const source = readFileSync(path, "utf8")
      expect(name).not.toMatch(/(?:^|\/)v2(?:\/|$)|-v2\b/i)
      expect(source).not.toMatch(/(?:from\s+["'][^"']*|import\s+["'][^"']*)ui\/v2/)
      if (name.endsWith(".css"))
        expect(source).not.toMatch(/--v2-|--text-mix-blend-mode|--(?:text|surface|syntax|markdown)-|--icon-base/)
    }
    const context = readFileSync(join(sourceRoot, "theme/context.tsx"), "utf8")
    const preload = readFileSync(join(root, "src/theme-preload.js"), "utf8")
    expect(context + preload).not.toMatch(/createElement\(["']style|appendChild|textContent|theme-cache|THEME_CACHE/)
  })
})

function walk(directory: string): string[] {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name)
    return statSync(path).isDirectory() ? walk(path) : [path]
  })
}
