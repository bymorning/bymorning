type AlphaToken = (typeof ALPHA_TOKENS)[number]
type PrimitiveToken = (typeof PRIMITIVE_TOKENS)[number]
type SemanticToken = (typeof SEMANTIC_TOKENS)[number]
type AvatarToken = Extract<SemanticToken, `color-avatar-${string}`>

export const AVATAR_TOKENS = SEMANTIC_TOKENS.filter((token): token is AvatarToken => token.startsWith("color-avatar-"))
const ALPHA_TOKEN_SET: ReadonlySet<string> = new Set(ALPHA_TOKENS)
const AVATAR_TOKEN_SET: ReadonlySet<string> = new Set(AVATAR_TOKENS)
export const NON_ALPHA_PRIMITIVE_TOKENS = PRIMITIVE_TOKENS.filter(
  (token): token is Exclude<PrimitiveToken, AlphaToken> => !ALPHA_TOKEN_SET.has(token),
)
export const THEME_SEMANTIC_TOKENS = SEMANTIC_TOKENS.filter(
  (token): token is Exclude<SemanticToken, AvatarToken> => !AVATAR_TOKEN_SET.has(token),
)
export const CANONICAL_TOKENS = [...PRIMITIVE_TOKENS, ...SEMANTIC_TOKENS]
export const THEME_SCOPED_TOKENS = [...NON_ALPHA_PRIMITIVE_TOKENS, ...THEME_SEMANTIC_TOKENS]
